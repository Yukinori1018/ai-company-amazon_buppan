def get_referral_rate(category_key: str, price: float = None) -> dict:
    """カテゴリキーから販売手数料設定を返す。未知のキーは default にフォールバック。

    price を渡さない場合（既存呼び出し側との後方互換）は、"rate" に代表値
    （本事業の主戦場=750円超、一部1,500円超の帯）を入れて返す。
    price を渡すと、そのカテゴリの "tiers" を見て段階料率を正確に適用した "rate" を返す
    （新設。既存の呼び出し側の挙動は一切変えない＝price省略時は今まで通り）。
    """
    cfg = REFERRAL_FEE_TABLE.get(category_key, REFERRAL_FEE_TABLE["default"])
    if price is None:
        return cfg
    tiers = cfg.get("tiers") or [(None, cfg["rate"])]
    rate = tiers[-1][1]
    for upper, r in tiers:
        if upper is None or price <= upper:
            rate = r
            break
    return {**cfg, "rate": rate}


def get_fba_fee(size_key: str) -> dict:
    """サイズキーから FBA 手数料設定を返す。未知のキーは standard_1 にフォールバック。"""
    return FBA_FEE_TABLE.get(size_key, FBA_FEE_TABLE["standard_1"])


def get_storage_fee_yen(volume_cm3: float, months: float,
                         size_class: str = "standard", peak_season: bool = True) -> float:
    """FBA在庫保管手数料の推定額（円）。新設関数（既存呼び出し側には影響しない）。

    volume_cm3: 商品1個の体積（cm³）。months: 保管月数。
    size_class: "standard" / "large" / "apparel"。peak_season: Trueなら繁忙期レート（保守側）。
    """
    rates = STORAGE_FEE_YEN_PER_1000CM3_MONTH.get(size_class, STORAGE_FEE_YEN_PER_1000CM3_MONTH["standard"])
    unit = rates["peak"] if peak_season else rates["regular"]
    return (volume_cm3 / 1000.0) * unit * months


