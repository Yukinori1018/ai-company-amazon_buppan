def band(yen) -> str:
    """発注額は帯で出す（実額は会員限定の取引条件そのもの）。"""
    yen = R._num(yen)
    if not yen:
        return "未算定"
    for lo, hi, label in ((0, 5000, "5千円未満"), (5000, 10000, "5千〜1万円"),
                          (10000, 15000, "1万〜1.5万円"), (15000, 20000, "1.5万〜2万円"),
                          (20000, 30000, "2万〜3万円"), (30000, 50000, "3万〜5万円")):
        if lo <= yen < hi:
            return label
    return "5万円以上"


def set_label(row: dict) -> str:
    n = R._num(row.get("Amazon側のセット数(Amazon1個=卸何点か)"))
    conf = row.get("セット数の確度") or "不明"
    if n == 1:
        return f"単品（Amazon 1個＝卸1点・確度{conf}）"
    if n and n > 1:
        return f"{int(n)}個セット（Amazon 1個＝卸{int(n)}点・確度{conf}）"
    return "未確定（人が両方の画面を見る）"


def cell(v, suffix: str = "") -> str:
    if v in (None, "", "nan"):
        return UNKNOWN_CELL
    return f"{v}{suffix}"


